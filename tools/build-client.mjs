/**
 * Build the browser half (`lib/client.js`) from the single source of truth
 * (`lib/boot.js` + `lib/boot.css`).
 *
 *   node tools/build-client.mjs
 *
 * The output is a module-loader bundle: the shell imports it, calls the
 * factory, and the boot screen mounts. No bundler, no dependencies.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const manifest = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'));

const boot = readFileSync(new URL('lib/boot.js', root), 'utf8');
const css = readFileSync(new URL('lib/boot.css', root), 'utf8');
const portrait = readFileSync(new URL('lib/assets/portrait.b64', root), 'utf8').trim();

// Defaults baked into the client half: a client module never sees the host
// config, so it plays with the same defaults the index row would receive.
const config = {
  enabled: true,
  speed: 1,
  oncePerSession: false,
  skippable: true,
  sound: 'ask',
  inline: false,
};

const out = `/* generated by tools/build-client.mjs — edit lib/boot.js / lib/boot.css instead */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(manifest.name)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

    if (!globalThis.__DSH_BOOT_SCREEN__) globalThis.__DSH_BOOT_SCREEN__ = ${JSON.stringify(config)};
    if (!globalThis.__DSH_BOOT_PORTRAIT__) globalThis.__DSH_BOOT_PORTRAIT__ = "data:image/webp;base64,${portrait}";

    // Style the overlay even when no index row injected it (desktop shell).
    if (!document.querySelector("style[data-dsh-boot-screen]")) {
      var style = document.createElement("style");
      style.setAttribute("data-dsh-boot-screen", "");
      style.textContent = ${JSON.stringify(css)};
      (document.head || document.documentElement).appendChild(style);
    }

/* ---- lib/boot.js ---- */
${boot}
/* ---- end lib/boot.js ---- */

    exports.inject = [];
    exports.apply = function apply() {};
    return module.exports;
  }
});
`;

const target = fileURLToPath(new URL('lib/client.js', root));
writeFileSync(target, out);
console.log('wrote', target, out.length, 'bytes');
